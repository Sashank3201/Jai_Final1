// Generates src/styles/tokens.generated.css from src/strands/tokens.ts.
//   node scripts/build-tokens.ts           write the file
//   node scripts/build-tokens.ts --check   fail if the file is stale or DESIGN.md disagrees with tokens.ts
import { readFile, writeFile } from 'node:fs/promises';
import { strandTokens, tear, type StrandTokens } from '../src/strands/tokens.ts';

const kebab = (s: string) => s.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`);
const rem = (px: number) => `${+(px / 16).toFixed(4)}rem`;

function luminance(hex: string): number {
  const c = [1, 3, 5]
    .map((i) => parseInt(hex.slice(i, i + 2), 16) / 255)
    .map((v) => (v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  return 0.2126 * c[0]! + 0.7152 * c[1]! + 0.0722 * c[2]!;
}

function block(t: StrandTokens): string {
  const sel = `:root[data-mode='strand'][data-strand='${t.id}']`;
  const lines: string[] = [];
  lines.push(`color-scheme: ${luminance(t.color.bg) < 0.2 ? 'dark' : 'light'};`);
  for (const [k, v] of Object.entries(t.palette)) lines.push(`--p-${kebab(k)}: ${v};`);
  for (const [k, v] of Object.entries(t.color)) lines.push(`--${kebab(k)}: ${v};`);
  for (const [k, v] of Object.entries(t.font)) lines.push(`--font-${k}: ${v};`);
  for (const [k, v] of Object.entries(t.ease)) lines.push(`--ease-${kebab(k)}: ${v};`);
  for (const [k, v] of Object.entries(t.dur)) lines.push(`--dur-${k}: ${v};`);
  t.fs.forEach((v, i) => lines.push(`--fs-${i === 7 ? 'splash' : i}: ${v};`));
  t.space.forEach((v, i) => lines.push(`--space-${i + 1}: ${rem(v)};`));
  lines.push(`--gutter: ${t.gutter};`);
  lines.push(`--cols: ${t.columns.phone};`);
  const out = [`  ${sel} {`, ...lines.map((l) => `    ${l}`), '  }'];
  const bp = [
    ['600px', t.columns.tablet],
    ['1024px', t.columns.desk],
    ['1920px', t.columns.wall],
  ] as const;
  for (const [min, cols] of bp)
    out.push(`  @media (min-width: ${min}) { ${sel} { --cols: ${cols}; } }`);
  return out.join('\n');
}

const css = [
  '/* GENERATED by scripts/build-tokens.ts from src/strands/tokens.ts. Do not edit by hand. */',
  '@layer strand {',
  '  :root {',
  `    --tear-charge: ${tear.chargeMs}ms;`,
  `    --tear-ms: ${tear.tearMs}ms;`,
  `    --tear-settle: ${tear.settleMs}ms;`,
  `    --ease-charge: ${tear.easeCharge};`,
  `    --ease-tear: ${tear.easeTear};`,
  `    --ease-fade: ${tear.easeFade};`,
  `    --dur-fade: ${tear.fadeMs}ms;`,
  '  }',
  '@media screen {',
  ...Object.values(strandTokens).map(block),
  '}',
  '}',
  '',
].join('\n');

const target = new URL('../src/styles/tokens.generated.css', import.meta.url);

if (process.argv.includes('--check')) {
  const problems: string[] = [];
  const current = await readFile(target, 'utf8').catch(() => '');
  if (current !== css)
    problems.push('src/styles/tokens.generated.css is stale: run `node scripts/build-tokens.ts`.');
  const design = await readFile(new URL('../DESIGN.md', import.meta.url), 'utf8');
  for (const t of Object.values(strandTokens)) {
    const start = design.indexOf(`STRAND-${t.id} —`, design.indexOf('## 3.'));
    const end = design.indexOf('\n## ', start + 1);
    const section = design.slice(start, end).toUpperCase();
    for (const [k, v] of Object.entries(t.palette)) {
      if (!section.includes(v.toUpperCase()))
        problems.push(`DESIGN.md STRAND-${t.id} is missing ${k} ${v}`);
    }
    for (const [k, v] of Object.entries(t.ease)) {
      if (['snap', 'move', 'wipe'].includes(k)) continue;
      if (!section.includes(v.toUpperCase()))
        problems.push(`DESIGN.md STRAND-${t.id} is missing ease ${k}: ${v}`);
    }
  }
  if (problems.length) {
    console.error(problems.join('\n'));
    process.exit(1);
  }
  console.log('tokens: DESIGN.md, tokens.ts and tokens.generated.css agree');
} else {
  await writeFile(target, css);
  console.log('wrote src/styles/tokens.generated.css');
}
